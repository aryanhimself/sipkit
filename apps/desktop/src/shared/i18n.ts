export const DESKTOP_CATALOGUES: Record<'en' | 'ne', DesktopMessages> = { en, ne };

/** 'auto' → OS locale; anything starting with `ne` is Nepali, else English. */
export function resolveDesktopLocale(setting: string, osLocale: string): 'en' | 'ne' {
  const tag = (setting === 'auto' ? osLocale : setting).toLowerCase();
  return tag.startsWith('ne') ? 'ne' : 'en';
}

/** Translate with `{param}` substitution. Missing params are left as-is. */
export function translate(
  locale: 'en' | 'ne',
  key: DesktopMessageKey,
  params: Record<string, string | number> = {},
): string {
  const template = DESKTOP_CATALOGUES[locale][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}
